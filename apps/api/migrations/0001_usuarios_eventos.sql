-- 0001: identidad (usuarios, sesiones) y catálogo (eventos, zonas, fases, puertas, staff).
--
-- Convenciones de todo el esquema:
--   * IDs bigint IDENTITY "BY DEFAULT": la semilla inserta los IDs del dataset tal cual
--     y luego el runner de semilla reajusta las secuencias.
--   * Fechas siempre timestamptz (instantes absolutos; el cliente decide la zona horaria).
--   * Dinero en centésimos enteros: integer para precios unitarios, bigint para montos.
--   * Los estados son text + CHECK en lugar de ENUM: un CHECK se cambia en una migración
--     nueva sin las restricciones de ALTER TYPE ... ADD VALUE dentro de transacciones.
--   * El rol de aplicación `ticketing_app` lo crea el runner (necesita la contraseña del
--     volumen de secretos). Aquí solo se le dan permisos explícitos, tabla por tabla.

-- btree_gist permite combinar "=" sobre zona_id con "&&" sobre rangos en un EXCLUDE.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------------
-- Usuarios: una sola tabla para los cuatro roles. El rol se verifica en el servidor.
-- ---------------------------------------------------------------------------
CREATE TABLE usuarios (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          text        NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 200),
  email           text        NOT NULL CHECK (email = lower(btrim(email)) AND email LIKE '%_@_%'),
  password_hash   text        NOT NULL,
  rol             text        NOT NULL CHECK (rol IN ('asistente', 'staff', 'organizador', 'admin')),
  -- El staff pertenece a un organizador; solo puede asignarse a eventos de ese organizador.
  organizador_id  bigint      REFERENCES usuarios (id),
  activo          boolean     NOT NULL DEFAULT true,
  creado_en       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT usuarios_email_uk UNIQUE (email),
  CONSTRAINT usuarios_staff_tiene_organizador CHECK ((rol = 'staff') = (organizador_id IS NOT NULL))
);

-- Refresh tokens con rotación y detección de reuso.
--   * Se guarda solo el SHA-256 del token: un volcado de la tabla no da sesiones válidas.
--   * Cada login abre una familia. Cada refresh marca el token usado y emite uno nuevo
--     en la misma familia. Si llega un token ya usado, alguien lo copió: se revoca la
--     familia completa (el atacante y la víctima vuelven a hacer login).
--   * Logout = revocar la familia. Como el access token dura pocos minutos, el cierre
--     de sesión es efectivo sin mantener una lista negra de JWT.
CREATE TABLE refresh_tokens (
  id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  usuario_id      bigint      NOT NULL REFERENCES usuarios (id),
  familia_id      uuid        NOT NULL,
  token_hash      bytea       NOT NULL CHECK (length(token_hash) = 32),
  emitido_en      timestamptz NOT NULL DEFAULT now(),
  expira_en       timestamptz NOT NULL,
  usado_en        timestamptz,
  revocado_en     timestamptz,
  reemplazado_por uuid        REFERENCES refresh_tokens (id),
  CONSTRAINT refresh_tokens_hash_uk UNIQUE (token_hash),
  CONSTRAINT refresh_tokens_vigencia CHECK (expira_en > emitido_en)
);
CREATE INDEX refresh_tokens_familia_idx ON refresh_tokens (familia_id);
CREATE INDEX refresh_tokens_usuario_idx ON refresh_tokens (usuario_id);

-- ---------------------------------------------------------------------------
-- Eventos. `estado` es solo administrativo; "próximo / en venta / finalizado" se deriva
-- de las fechas en la API, para que nunca quede desfasado respecto del reloj.
-- ---------------------------------------------------------------------------
CREATE TABLE eventos (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo              text        NOT NULL CHECK (length(btrim(codigo)) BETWEEN 1 AND 40),
  nombre              text        NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 200),
  organizador_id      bigint      NOT NULL REFERENCES usuarios (id),
  recinto             text        NOT NULL,
  fecha               timestamptz NOT NULL,
  venta_abre          timestamptz NOT NULL,
  reembolsable_hasta  timestamptz NOT NULL,
  limite_por_cuenta   integer     NOT NULL CHECK (limite_por_cuenta BETWEEN 1 AND 100),
  estado              text        NOT NULL DEFAULT 'publicado'
                                  CHECK (estado IN ('borrador', 'publicado', 'cancelado')),
  creado_en           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT eventos_codigo_uk UNIQUE (codigo),
  CONSTRAINT eventos_fechas CHECK (venta_abre < fecha AND reembolsable_hasta <= fecha)
);
-- "Un organizador solo ve sus eventos": todo listado del portal filtra por organizador_id.
CREATE INDEX eventos_organizador_idx ON eventos (organizador_id, fecha);
-- La cartelera ordena por fecha.
CREATE INDEX eventos_fecha_idx ON eventos (fecha);

-- ---------------------------------------------------------------------------
-- Zonas: aquí vive el invariante 1.
--   vendidas   = entradas vigentes (pagada, transferida, usada).
--   reservadas = cupos retenidos por reservas activas.
-- La API nunca cuenta filas para decidir si hay cupo: hace
--   UPDATE zonas SET reservadas = reservadas + $n
--    WHERE id = $z AND vendidas + reservadas + $n <= aforo
-- y si afecta 0 filas responde 409. El UPDATE toma el lock de la fila, así que
-- compradores concurrentes de la misma zona se serializan solo en ese instante.
-- El CHECK es la red de seguridad: aunque un bug de código intentara sobrevender,
-- PostgreSQL abortaría la transacción. También impide bajar el aforo por debajo
-- de lo ya vendido/reservado.
-- ---------------------------------------------------------------------------
CREATE TABLE zonas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id   bigint  NOT NULL REFERENCES eventos (id),
  nombre      text    NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 120),
  aforo       integer NOT NULL CHECK (aforo > 0),
  vendidas    integer NOT NULL DEFAULT 0 CHECK (vendidas >= 0),
  reservadas  integer NOT NULL DEFAULT 0 CHECK (reservadas >= 0),
  CONSTRAINT zonas_nombre_uk UNIQUE (evento_id, nombre),
  CONSTRAINT zonas_no_sobreventa CHECK (vendidas + reservadas <= aforo),
  -- Clave compuesta para FKs (zona_id, evento_id): garantiza que una reserva, compra o
  -- entrada no pueda apuntar a una zona de otro evento.
  CONSTRAINT zonas_id_evento_uk UNIQUE (id, evento_id)
);

-- Fases de precio. El EXCLUDE garantiza que en una zona nunca hay dos fases vigentes
-- a la vez, así "la fase vigente al reservar" siempre es única (rango [desde, hasta)).
CREATE TABLE fases_precio (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zona_id            bigint      NOT NULL REFERENCES zonas (id),
  fase               text        NOT NULL CHECK (fase IN ('preventa', 'general', 'taquilla')),
  precio_centesimos  integer     NOT NULL CHECK (precio_centesimos >= 0),
  desde              timestamptz NOT NULL,
  hasta              timestamptz NOT NULL,
  CONSTRAINT fases_precio_rango CHECK (desde < hasta),
  CONSTRAINT fases_precio_fase_uk UNIQUE (zona_id, fase),
  CONSTRAINT fases_precio_sin_solape
    EXCLUDE USING gist (zona_id WITH =, tstzrange(desde, hasta, '[)') WITH &&)
);
-- El índice gist del EXCLUDE ya sirve para buscar la fase vigente de una zona.

CREATE TABLE puertas (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id  bigint NOT NULL REFERENCES eventos (id),
  nombre     text   NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 120),
  CONSTRAINT puertas_nombre_uk UNIQUE (evento_id, nombre),
  CONSTRAINT puertas_id_evento_uk UNIQUE (id, evento_id)
);

-- Qué staff puede escanear en qué evento. Que el staff sea del mismo organizador del
-- evento se valida en la API (un CHECK no puede mirar otras tablas).
CREATE TABLE asignaciones_staff (
  evento_id  bigint      NOT NULL REFERENCES eventos (id),
  staff_id   bigint      NOT NULL REFERENCES usuarios (id),
  creado_en  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (evento_id, staff_id)
);
CREATE INDEX asignaciones_staff_staff_idx ON asignaciones_staff (staff_id);

-- ---------------------------------------------------------------------------
-- Permisos del rol de aplicación (mínimo privilegio, explícito por tabla).
-- ---------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE         ON usuarios, eventos, zonas, fases_precio, puertas TO ticketing_app;
GRANT SELECT, INSERT, UPDATE         ON refresh_tokens                                  TO ticketing_app;
GRANT SELECT, INSERT, DELETE         ON asignaciones_staff                              TO ticketing_app;
GRANT USAGE                          ON SEQUENCE usuarios_id_seq, eventos_id_seq, zonas_id_seq,
                                        fases_precio_id_seq, puertas_id_seq           TO ticketing_app;
