-- 0003: entradas, transferencias, reembolsos, revocaciones y control de acceso
-- (invariantes 3 y 4).

-- ---------------------------------------------------------------------------
-- Entradas.
-- Código rotativo (invariante 3), sin que ninguna llave privada viaje:
--   * El teléfono del titular genera un par Ed25519 propio; solo envía la pública.
--     Se guarda en `dispositivo_pubkey` (32 bytes crudos).
--   * El servidor firma con SU llave una credencial {entrada, evento, zona, version,
--     dispositivo_pubkey}. El escáner la verifica con la llave pública del servidor.
--   * Cada 15 s la app firma {credencial, timestamp} con la llave del dispositivo; el
--     escáner exige ambas firmas y un timestamp dentro de su ventana. Una captura de
--     hace un minuto queda fuera de la ventana; copiar la credencial a otro teléfono
--     no sirve porque falta la llave privada del dispositivo.
--   * `version` sube cuando cambia el titular (transferencia) o el dispositivo vinculado.
--     Las versiones anteriores se publican en `revocaciones`, así los escáneres que ya
--     sincronizaron rechazan la credencial vieja.
-- ---------------------------------------------------------------------------
CREATE TABLE entradas (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id           bigint      NOT NULL REFERENCES compras (id),
  evento_id           bigint      NOT NULL REFERENCES eventos (id),
  zona_id             bigint      NOT NULL,
  comprador_id        bigint      NOT NULL REFERENCES usuarios (id),
  titular_id          bigint      NOT NULL REFERENCES usuarios (id),
  -- pagada: vigente con el comprador. transferida: vigente con otro usuario.
  -- usada: ya ingresó. reembolsada / anulada: fuera de circulación, liberan cupo.
  estado              text        NOT NULL
                                  CHECK (estado IN ('pagada', 'transferida', 'usada', 'reembolsada', 'anulada')),
  version             integer     NOT NULL DEFAULT 1 CHECK (version >= 1),
  dispositivo_pubkey  bytea       CHECK (length(dispositivo_pubkey) = 32),
  precio_centesimos   integer     NOT NULL CHECK (precio_centesimos >= 0),
  emitida_en          timestamptz NOT NULL DEFAULT now(),
  usada_en            timestamptz,
  anulada_en          timestamptz,
  CONSTRAINT entradas_zona_fk FOREIGN KEY (zona_id, evento_id) REFERENCES zonas (id, evento_id),
  CONSTRAINT entradas_usada CHECK ((estado = 'usada') = (usada_en IS NOT NULL)),
  CONSTRAINT entradas_anulada CHECK ((estado IN ('reembolsada', 'anulada')) = (anulada_en IS NOT NULL)),
  CONSTRAINT entradas_titular CHECK (
    (estado = 'pagada' AND titular_id = comprador_id) OR
    (estado = 'transferida' AND titular_id <> comprador_id) OR
    estado IN ('usada', 'reembolsada', 'anulada'))
);
-- Billetera: "mis entradas".
CREATE INDEX entradas_titular_idx ON entradas (titular_id, evento_id);
CREATE INDEX entradas_compra_idx ON entradas (compra_id);
-- Portal: buscar entradas por comprador y reportes por evento/zona/estado.
CREATE INDEX entradas_comprador_idx ON entradas (comprador_id);
CREATE INDEX entradas_evento_idx ON entradas (evento_id, zona_id, estado);

-- ---------------------------------------------------------------------------
-- Transferencias por correo. La entrada cambia de titular solo al aceptar.
-- Solo una transferencia pendiente por entrada (índice único parcial): dos solicitudes
-- simultáneas sobre la misma entrada no pueden quedar ambas abiertas.
-- ---------------------------------------------------------------------------
CREATE TABLE transferencias (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrada_id     bigint      NOT NULL REFERENCES entradas (id),
  de_usuario_id  bigint      NOT NULL REFERENCES usuarios (id),
  a_usuario_id   bigint      NOT NULL REFERENCES usuarios (id),
  estado         text        NOT NULL DEFAULT 'pendiente'
                             CHECK (estado IN ('pendiente', 'aceptada', 'cancelada', 'rechazada')),
  creada_en      timestamptz NOT NULL DEFAULT now(),
  resuelta_en    timestamptz,
  CONSTRAINT transferencias_distintos CHECK (de_usuario_id <> a_usuario_id),
  CONSTRAINT transferencias_resuelta CHECK ((estado = 'pendiente') = (resuelta_en IS NULL))
);
CREATE UNIQUE INDEX transferencias_una_pendiente_uk ON transferencias (entrada_id) WHERE estado = 'pendiente';
CREATE INDEX transferencias_destino_idx ON transferencias (a_usuario_id, estado);
CREATE INDEX transferencias_origen_idx ON transferencias (de_usuario_id, estado);

-- ---------------------------------------------------------------------------
-- Reembolsos, con motivo y autor (NULL = sistema, p. ej. pago tardío sin cupo).
--   * UNIQUE (entrada_id): una entrada se reembolsa una sola vez aunque se repita la
--     petición con otra clave de idempotencia.
--   * El reembolso automático de una compra sin entradas usa entrada_id NULL y es único
--     por compra.
-- "Nunca después de usada": la API hace UPDATE entradas SET estado = 'reembolsada'
-- WHERE id = $1 AND estado IN ('pagada', 'transferida'); si la entrada está 'usada'
-- afecta 0 filas y responde 409.
-- ---------------------------------------------------------------------------
CREATE TABLE reembolsos (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id         bigint      NOT NULL REFERENCES compras (id),
  entrada_id        bigint      REFERENCES entradas (id),
  monto_centesimos  bigint      NOT NULL CHECK (monto_centesimos >= 0),
  motivo            text        NOT NULL CHECK (length(btrim(motivo)) BETWEEN 1 AND 500),
  autor_id          bigint      REFERENCES usuarios (id),
  creado_en         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reembolsos_entrada_uk UNIQUE (entrada_id)
);
CREATE UNIQUE INDEX reembolsos_automatico_uk ON reembolsos (compra_id) WHERE entrada_id IS NULL;
CREATE INDEX reembolsos_compra_idx ON reembolsos (compra_id);

-- ---------------------------------------------------------------------------
-- Revocaciones incrementales para los escáneres.
-- Cada fila dice "de esta entrada, rechazar toda credencial con version < version_minima"
-- (transferencia o cambio de dispositivo) o "rechazar la entrada completa" (reembolso,
-- anulación). El escáner guarda el último `id` visto y pide solo lo nuevo de su evento.
--
-- Cuidado con el cursor: un bigserial no se confirma en orden (la transacción con id 10
-- puede hacer COMMIT después de que alguien ya leyó el 11, y el 10 se perdería). Para
-- evitarlo la API inserta revocaciones tomando pg_advisory_xact_lock(evento_id): dentro
-- de un evento las inserciones se serializan hasta el COMMIT, así el orden de los ids
-- coincide con el de confirmación. Las revocaciones son raras, el costo es despreciable.
-- ---------------------------------------------------------------------------
CREATE TABLE revocaciones (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  evento_id       bigint      NOT NULL REFERENCES eventos (id),
  entrada_id      bigint      NOT NULL REFERENCES entradas (id),
  tipo            text        NOT NULL CHECK (tipo IN ('version', 'entrada')),
  version_minima  integer     CHECK (version_minima >= 1),
  motivo          text        NOT NULL CHECK (motivo IN ('transferencia', 'dispositivo', 'reembolso', 'anulacion')),
  creada_en       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT revocaciones_version CHECK ((tipo = 'version') = (version_minima IS NOT NULL))
);
-- "Bajar revocaciones desde el cursor X para el evento Y".
CREATE INDEX revocaciones_evento_cursor_idx ON revocaciones (evento_id, id);

-- ---------------------------------------------------------------------------
-- Dispositivos de escaneo y turnos. "Quién escaneó qué": cada ingreso apunta al turno
-- (staff + puerta + dispositivo). `ultima_sync` alimenta el panel de dispositivos y la
-- detección de escáneres desincronizados.
-- ---------------------------------------------------------------------------
CREATE TABLE dispositivos (
  id                    uuid        PRIMARY KEY,  -- lo genera el teléfono al registrarse
  staff_id              bigint      NOT NULL REFERENCES usuarios (id),
  nombre                text        NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 120),
  plataforma            text,
  registrado_en         timestamptz NOT NULL DEFAULT now(),
  ultima_sync           timestamptz,
  cursor_revocaciones   bigint      NOT NULL DEFAULT 0
);
CREATE INDEX dispositivos_staff_idx ON dispositivos (staff_id);

CREATE TABLE turnos (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id        bigint      NOT NULL REFERENCES usuarios (id),
  evento_id       bigint      NOT NULL REFERENCES eventos (id),
  puerta_id       bigint      NOT NULL,
  dispositivo_id  uuid        NOT NULL REFERENCES dispositivos (id),
  inicio          timestamptz NOT NULL DEFAULT now(),
  fin             timestamptz,
  CONSTRAINT turnos_puerta_fk FOREIGN KEY (puerta_id, evento_id) REFERENCES puertas (id, evento_id),
  CONSTRAINT turnos_staff_asignado_fk FOREIGN KEY (evento_id, staff_id)
    REFERENCES asignaciones_staff (evento_id, staff_id),
  CONSTRAINT turnos_rango CHECK (fin IS NULL OR fin > inicio)
);
-- Un dispositivo tiene como máximo un turno abierto.
CREATE UNIQUE INDEX turnos_dispositivo_abierto_uk ON turnos (dispositivo_id) WHERE fin IS NULL;
CREATE INDEX turnos_evento_idx ON turnos (evento_id, puerta_id);

-- ---------------------------------------------------------------------------
-- Ingresos (invariante 4).
--   * client_scan_id UNIQUE: el teléfono genera un UUID por escaneo. Reenviar el lote
--     hace INSERT ... ON CONFLICT (client_scan_id) DO NOTHING: no duplica nada.
--   * Índice único parcial: como máximo UN ingreso 'valido' por entrada. Si dos puertas
--     offline dejaron pasar la misma entrada, el segundo en sincronizar no puede ser
--     'valido': se guarda como 'duplicado_offline' y se abre un incidente. Nunca se borra.
--   * Los rechazos locales (firma inválida, revocada, expirada, otro evento) también se
--     suben como 'rechazado' con su motivo, para el panel de incidentes y auditoría.
-- ---------------------------------------------------------------------------
CREATE TABLE ingresos (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_scan_id   text        NOT NULL CHECK (length(client_scan_id) BETWEEN 1 AND 100),
  entrada_id       bigint      REFERENCES entradas (id),  -- NULL si la firma no permitió identificarla
  evento_id        bigint      NOT NULL REFERENCES eventos (id),
  puerta_id        bigint      NOT NULL,
  staff_id         bigint      NOT NULL REFERENCES usuarios (id),
  dispositivo_id   uuid        REFERENCES dispositivos (id),  -- NULL en ingresos históricos de la semilla
  turno_id         bigint      REFERENCES turnos (id),
  version_entrada  integer,
  resultado        text        NOT NULL CHECK (resultado IN ('valido', 'duplicado_offline', 'rechazado')),
  motivo_rechazo   text        CHECK (motivo_rechazo IN
                                 ('firma_invalida', 'expirado', 'revocada', 'ya_usada', 'otro_evento', 'otra_zona')),
  escaneado_en     timestamptz NOT NULL,   -- reloj del dispositivo
  sincronizado_en  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ingresos_client_scan_uk UNIQUE (client_scan_id),
  CONSTRAINT ingresos_puerta_fk FOREIGN KEY (puerta_id, evento_id) REFERENCES puertas (id, evento_id),
  CONSTRAINT ingresos_motivo CHECK ((resultado = 'rechazado') = (motivo_rechazo IS NOT NULL)),
  CONSTRAINT ingresos_entrada CHECK (resultado = 'rechazado' OR entrada_id IS NOT NULL)
);
CREATE UNIQUE INDEX ingresos_un_valido_por_entrada_uk ON ingresos (entrada_id) WHERE resultado = 'valido';
-- Portal: ingresos por puerta y por hora.
CREATE INDEX ingresos_evento_tiempo_idx ON ingresos (evento_id, escaneado_en);
CREATE INDEX ingresos_entrada_idx ON ingresos (entrada_id);

-- ---------------------------------------------------------------------------
-- Incidentes visibles en el portal.
-- ---------------------------------------------------------------------------
CREATE TABLE incidentes (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo            text        NOT NULL CHECK (tipo IN
                                ('doble_ingreso', 'firma_invalida', 'escaner_desincronizado', 'pico_compra')),
  evento_id       bigint      NOT NULL REFERENCES eventos (id),
  entrada_id      bigint      REFERENCES entradas (id),
  ingreso_id      bigint      REFERENCES ingresos (id),
  dispositivo_id  uuid        REFERENCES dispositivos (id),
  detalle         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  estado          text        NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto', 'resuelto')),
  creado_en       timestamptz NOT NULL DEFAULT now(),
  resuelto_en     timestamptz,
  resuelto_por    bigint      REFERENCES usuarios (id),
  CONSTRAINT incidentes_resuelto CHECK ((estado = 'resuelto') = (resuelto_en IS NOT NULL))
);
-- Un ingreso genera como máximo un incidente de cada tipo (reprocesar un lote no duplica).
CREATE UNIQUE INDEX incidentes_por_ingreso_uk ON incidentes (tipo, ingreso_id) WHERE ingreso_id IS NOT NULL;
CREATE INDEX incidentes_evento_idx ON incidentes (evento_id, creado_en DESC);

GRANT SELECT, INSERT, UPDATE ON entradas, transferencias, dispositivos, turnos, incidentes TO ticketing_app;
-- Reembolsos, revocaciones e ingresos son hechos: la app los crea y los lee, no los edita.
GRANT SELECT, INSERT ON reembolsos, revocaciones, ingresos TO ticketing_app;
GRANT USAGE ON SEQUENCE entradas_id_seq, transferencias_id_seq, reembolsos_id_seq, revocaciones_id_seq,
                        turnos_id_seq, ingresos_id_seq, incidentes_id_seq TO ticketing_app;
