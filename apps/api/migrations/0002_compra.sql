-- 0002: flujo de compra (invariantes 1 y 2): cupo por cuenta, reservas y compras.
--
-- Flujo: reservar (retiene cupo y congela precio) -> pagar (simulado) -> emitir entradas.
-- Todo cambio de cupo se hace con UPDATE/UPSERT condicionales; nunca "SELECT y luego INSERT".

-- ---------------------------------------------------------------------------
-- Límite de entradas por cuenta y por evento, aplicado bajo concurrencia.
-- `usadas` cuenta entradas vigentes compradas + cupos en reservas activas del usuario.
-- La API hace un UPSERT condicional:
--   INSERT INTO cupo_cuenta (usuario_id, evento_id, usadas)
--   SELECT $u, $e, $n FROM eventos WHERE id = $e AND $n <= limite_por_cuenta
--   ON CONFLICT (usuario_id, evento_id) DO UPDATE
--     SET usadas = cupo_cuenta.usadas + EXCLUDED.usadas
--     WHERE cupo_cuenta.usadas + EXCLUDED.usadas <= (SELECT limite_por_cuenta FROM eventos WHERE id = $e)
-- 0 filas afectadas = límite alcanzado. Dos pestañas del mismo usuario comprando a la vez
-- chocan en la misma fila y se serializan; una de las dos queda fuera.
-- El límite se cuenta sobre el comprador: recibir entradas por transferencia no consume cupo.
-- ---------------------------------------------------------------------------
CREATE TABLE cupo_cuenta (
  usuario_id  bigint  NOT NULL REFERENCES usuarios (id),
  evento_id   bigint  NOT NULL REFERENCES eventos (id),
  usadas      integer NOT NULL CHECK (usadas >= 0),
  PRIMARY KEY (usuario_id, evento_id)
);

-- ---------------------------------------------------------------------------
-- Reservas temporales. El precio se congela aquí, calculado por el servidor a partir de
-- la fase vigente en `creada_en`; el pago cobra este monto y nunca uno del cliente.
--
-- Expiración (confiable aunque el proceso se reinicie):
--   1. Vigencia por consulta: una reserva con expira_en <= now() no se puede pagar,
--      aunque nadie la haya barrido todavía.
--   2. Un barrido periódico toma las vencidas con FOR UPDATE SKIP LOCKED, las marca
--      'expirada' y devuelve el cupo a zonas.reservadas y a cupo_cuenta en la misma
--      transacción. Si el proceso muere a mitad, la transacción se revierte y el
--      siguiente barrido (o la siguiente instancia) la retoma: no hay estado en memoria.
-- ---------------------------------------------------------------------------
CREATE TABLE reservas (
  id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id                  bigint      NOT NULL REFERENCES usuarios (id),
  evento_id                   bigint      NOT NULL REFERENCES eventos (id),
  zona_id                     bigint      NOT NULL,
  fase_precio_id              bigint      NOT NULL REFERENCES fases_precio (id),
  cantidad                    integer     NOT NULL CHECK (cantidad BETWEEN 1 AND 100),
  precio_unitario_centesimos  integer     NOT NULL CHECK (precio_unitario_centesimos >= 0),
  monto_centesimos            bigint      NOT NULL,
  idempotency_key             text        NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 200),
  estado                      text        NOT NULL DEFAULT 'activa'
                                          CHECK (estado IN ('activa', 'pagada', 'expirada', 'cancelada')),
  creada_en                   timestamptz NOT NULL DEFAULT now(),
  expira_en                   timestamptz NOT NULL,
  resuelta_en                 timestamptz,
  CONSTRAINT reservas_zona_fk FOREIGN KEY (zona_id, evento_id) REFERENCES zonas (id, evento_id),
  CONSTRAINT reservas_monto CHECK (monto_centesimos = cantidad::bigint * precio_unitario_centesimos),
  CONSTRAINT reservas_vigencia CHECK (expira_en > creada_en),
  CONSTRAINT reservas_resuelta CHECK ((estado = 'activa') = (resuelta_en IS NULL)),
  -- Doble toque en "reservar": la segunda petición con la misma clave choca aquí.
  CONSTRAINT reservas_idempotencia_uk UNIQUE (usuario_id, idempotency_key)
);
-- El barrido solo recorre reservas activas, ordenadas por vencimiento (índice parcial
-- pequeño: las expiradas/pagadas no ocupan espacio en él).
CREATE INDEX reservas_activas_expira_idx ON reservas (expira_en) WHERE estado = 'activa';
CREATE INDEX reservas_usuario_idx ON reservas (usuario_id, creada_en DESC);

-- ---------------------------------------------------------------------------
-- Compras (pago simulado). Garantías de cobro único:
--   * UNIQUE (usuario_id, idempotency_key): reintentos con la misma clave no crean otra compra.
--   * UNIQUE (reserva_id): aunque el cliente use claves distintas, una reserva se paga una
--     sola vez. (Las compras históricas de la semilla no tienen reserva: NULL no choca.)
--   * El monto se copia de la reserva; el cliente no envía montos.
--
-- Política de pago tardío (la reserva ya expiró cuando llega el pago):
--   se intenta re-reservar el cupo con el mismo UPDATE condicional de zonas y cupo_cuenta.
--   Si hay cupo, se emite normalmente. Si no, la compra queda 'reembolso_automatico'
--   (cobro registrado y devuelto, sin entradas). En ambos casos la misma clave de
--   idempotencia devuelve siempre el mismo resultado.
-- ---------------------------------------------------------------------------
CREATE TABLE compras (
  id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id                  bigint      NOT NULL REFERENCES usuarios (id),
  evento_id                   bigint      NOT NULL REFERENCES eventos (id),
  zona_id                     bigint      NOT NULL,
  reserva_id                  bigint      REFERENCES reservas (id),
  fase_precio_id              bigint      NOT NULL REFERENCES fases_precio (id),
  cantidad                    integer     NOT NULL CHECK (cantidad BETWEEN 1 AND 100),
  precio_unitario_centesimos  integer     NOT NULL CHECK (precio_unitario_centesimos >= 0),
  monto_centesimos            bigint      NOT NULL,
  idempotency_key             text        NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 200),
  -- pagada: entradas emitidas (alguna puede reembolsarse después, ver tabla reembolsos).
  -- reembolsada: todas sus entradas fueron reembolsadas.
  -- reembolso_automatico: pago tardío sin cupo; no se emitió ninguna entrada.
  estado                      text        NOT NULL
                                          CHECK (estado IN ('pagada', 'reembolsada', 'reembolso_automatico')),
  referencia_pago             text,
  pagada_en                   timestamptz NOT NULL DEFAULT now(),
  reembolsada_en              timestamptz,
  CONSTRAINT compras_zona_fk FOREIGN KEY (zona_id, evento_id) REFERENCES zonas (id, evento_id),
  CONSTRAINT compras_monto CHECK (monto_centesimos = cantidad::bigint * precio_unitario_centesimos),
  CONSTRAINT compras_reembolso CHECK ((estado = 'pagada') = (reembolsada_en IS NULL)),
  CONSTRAINT compras_idempotencia_uk UNIQUE (usuario_id, idempotency_key),
  CONSTRAINT compras_reserva_uk UNIQUE (reserva_id)
);
-- Historial de compras del usuario (paginación por cursor sobre (pagada_en, id)).
CREATE INDEX compras_usuario_idx ON compras (usuario_id, pagada_en DESC, id DESC);
-- Ingresos por evento/zona en el portal.
CREATE INDEX compras_evento_idx ON compras (evento_id, zona_id);

GRANT SELECT, INSERT, UPDATE ON cupo_cuenta, reservas, compras TO ticketing_app;
GRANT USAGE ON SEQUENCE reservas_id_seq, compras_id_seq TO ticketing_app;
